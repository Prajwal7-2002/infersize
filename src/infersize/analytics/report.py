"""Architecture RFC and Capacity Sizing Report Generator."""

from __future__ import annotations

from datetime import datetime, timezone

from pydantic import BaseModel, Field

from infersize import __version__
from infersize.analytics.comparison import (
    GPUComparisonReport,
    compare_gpus_for_workload,
)
from infersize.analytics.cost import (
    CostEstimateResult,
    MultiGPUCostReport,
    compare_cloud_costs_for_workload,
    estimate_serving_cost,
)
from infersize.analytics.vram import (
    VRAMEstimateResult,
    estimate_vram_usage,
)
from infersize.hardware.pricing import CLOUD_GPU_PRICING
from infersize.hardware.specs import GPUProfile
from infersize.models.specs import ModelArch


class ArchitectureReport(BaseModel):
    """Complete deployment specification and RFC capacity sizing report."""

    title: str = Field(default="Architecture RFC: LLM Capacity Planning & Sizing Specification")
    generated_at_utc: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    )
    infersize_version: str = Field(default=__version__)

    # Workload parameters
    model_name: str
    gpu_name: str
    gpu_id: str
    precision: str
    kv_cache_dtype: str
    batch_size: int
    context_tokens: int
    tensor_parallel: int
    provider: str

    # Sub-analytics
    vram_estimate: VRAMEstimateResult
    cost_estimate: CostEstimateResult
    gpu_comparison: GPUComparisonReport
    cloud_cost_comparison: MultiGPUCostReport

    # Model architecture summary
    total_parameters: int
    num_layers: int
    hidden_size: int
    num_attention_heads: int
    num_kv_heads: int
    gqa_ratio: float
    mlp_type: str

    def to_markdown(self) -> str:
        """Render complete specification into publication-ready GitHub-flavored Markdown."""
        lines = [
            f"# {self.title}",
            "",
            f"> **Generated by `infersize` v{self.infersize_version}** on {self.generated_at_utc}.  ",
            "> *Analytical pre-flight capacity planning & physical hardware sizing before deployment.*",
            "",
            "---",
            "",
            "## 1. Executive Summary & Workload Definition",
            "",
            f"This document provides the hardware sizing, physical memory breakdown, and cloud unit economics for serving **`{self.model_name}`** under the target production profile below:",
            "",
            "| Parameter | Target Specification | Physical Implication |",
            "|:---|:---|:---|",
            f"| **Target Model** | `{self.model_name}` ({self.total_parameters / 1e9:.2f}B params) | Architecture: {self.num_layers} layers, hidden={self.hidden_size} |",
            f"| **Primary Accelerator** | `{self.gpu_name}` | Physical VRAM: {self.vram_estimate.gpu_total_vram_gb:.1f} GB ({self.vram_estimate.vram_utilization_pct:.1f}% utilized) |",
            f"| **Weight Precision** | `{self.precision.upper()}` | Compression: {self.vram_estimate.weight_compression_ratio:.1f}x vs FP16 baseline |",
            f"| **KV-Cache Dtype** | `{self.kv_cache_dtype.upper()}` | Consumes {self.vram_estimate.kv_bytes_per_token:,} bytes/token per sequence |",
            f"| **Concurrent Streams** | `Batch Size = {self.batch_size}` | Peak aggregate throughput across active requests |",
            f"| **Target Context Window** | `{self.context_tokens:,}` tokens | Maximum supported prompt + generation budget |",
            f"| **Tensor Parallelism (TP)** | `{self.tensor_parallel}` GPU(s) | Memory and parameters partitioned across cluster |",
            f"| **Cloud Provider** | `{self.provider.upper()}` | Baseline rate: ${self.cost_estimate.total_cluster_hourly_usd:.2f}/hr |",
            "",
            "---",
            "",
            "## 2. Transformer Architecture & Parameter Accounting",
            "",
            "Physical parameter accounting derived directly from architectural specifications:",
            "",
            f"- **Attention Mechanism**: {self.num_attention_heads} Query Heads, {self.num_kv_heads} KV Heads "
            f"(**Grouped-Query Attention Ratio: {self.gqa_ratio:.1f}x**).",
            f"- **Feed-Forward Network (FFN)**: `{self.mlp_type.upper()}` "
            f"({'3 matrices (Gate, Up, Down)' if self.mlp_type == 'swiglu' else '2 matrices (FC, Proj)'}).",
            f"- **Total Model Weights**: **{self.total_parameters:,} parameters** ({self.vram_estimate.weight_memory_gb:.2f} GB in {self.precision.upper()}).",
            "",
            "---",
            "",
            "## 3. Physical VRAM Allocation Breakdown",
            "",
            f"Memory budget distribution on **{self.gpu_name}**:",
            "",
            "| Memory Component | Allocation (GB) | Share of VRAM (%) | Engineering Note |",
            "|:---|---:|---:|:---|",
            f"| **Model Weights** | {self.vram_estimate.weight_memory_gb:.2f} GB | {(self.vram_estimate.weight_memory_gb / self.vram_estimate.gpu_total_vram_gb) * 100:.1f}% | Static physical footprint partitioned across TP={self.tensor_parallel} |",
            f"| **KV-Cache** | {self.vram_estimate.kv_cache_memory_gb:.2f} GB | {(self.vram_estimate.kv_cache_memory_gb / self.vram_estimate.gpu_total_vram_gb) * 100:.1f}% | Dynamic cache for {self.batch_size} streams x {self.context_tokens:,} tokens |",
            f"| **Activations Buffer** | {self.vram_estimate.activation_memory_gb:.2f} GB | {(self.vram_estimate.activation_memory_gb / self.vram_estimate.gpu_total_vram_gb) * 100:.1f}% | FlashAttention linear working memory buffer |",
            f"| **CUDA Context Overhead** | {self.vram_estimate.cuda_overhead_gb:.2f} GB | {(self.vram_estimate.cuda_overhead_gb / self.vram_estimate.gpu_total_vram_gb) * 100:.1f}% | Driver context, runtime allocations & cuBLAS workspace |",
            "| **TOTAL REQUIRED** | **"
            + f"{self.vram_estimate.total_required_vram_gb:.2f} GB** | **"
            + f"{self.vram_estimate.vram_utilization_pct:.1f}%** | "
            + ("**✔ Fits safely**" if self.vram_estimate.fits_in_vram else "**✘ OOM Deficit**")
            + " |",
            f"| **FREE HEADROOM** | **{'+' if self.vram_estimate.free_vram_headroom_gb >= 0 else ''}{self.vram_estimate.free_vram_headroom_gb:.2f} GB** | {100.0 - self.vram_estimate.vram_utilization_pct:.1f}% | Available headroom for concurrency bursts |",
            "",
            "---",
            "",
            "## 4. Multi-Accelerator Comparison Matrix",
            "",
            "Evaluation of candidate accelerators under the target serving workload:",
            "",
            self.gpu_comparison.to_markdown_table(),
            "",
            "---",
            "",
            "## 5. Decode Roofline Throughput & Cloud Unit Economics",
            "",
            "Autoregressive generation performance and cloud hosting economics:",
            "",
            "| Metric | Value | Physical & Financial Meaning |",
            "|:---|---:|:---|",
            f"| **Peak Memory Bandwidth** | {self.cost_estimate.memory_bandwidth_gb_s:.0f} GB/s | Theoretical memory bus transfer limit |",
            f"| **Effective Bandwidth (η=0.80)** | {self.cost_estimate.effective_bandwidth_gb_s:.1f} GB/s | Real-world achievable bandwidth in inference engines |",
            f"| **DRAM Transfer / Step** | {self.cost_estimate.total_dram_bytes_per_step / 1e9:.2f} GB | Total bytes fetched from HBM per token step |",
            f"| **Time Per Output Token (TPOT)** | **{self.cost_estimate.time_per_output_token_ms:.1f} ms** | Latency per generated token per user stream |",
            f"| **User Generation Speed** | **{self.cost_estimate.tokens_per_sec_per_user:.1f} tok/s** | User-perceived output streaming speed |",
            f"| **Aggregate Batch Throughput** | **{self.cost_estimate.aggregate_tokens_per_sec:.1f} tok/s** | Total throughput generated across all B={self.batch_size} streams |",
            f"| **Hourly Generation Capacity** | **{self.cost_estimate.tokens_per_hour:,.0f} tokens/hr** | Maximum token volume per continuous operating hour |",
            f"| **Cluster Rental Cost** | **${self.cost_estimate.total_cluster_hourly_usd:.2f} / hr** | ${self.cost_estimate.hourly_rate_usd:.2f}/hr x {self.tensor_parallel} GPU(s) ({self.provider.upper()}) |",
            f"| **COST PER 1M TOKENS** | **${self.cost_estimate.cost_per_million_tokens_usd:.4f}** | **Direct operational cost per million generated tokens** |",
            f"| **24/7 Dedicated Monthly Cost** | **${self.cost_estimate.monthly_dedicated_cost_usd:.2f} / mo** | Baseline idle cloud rental cost (730 continuous hours) |",
            "",
            "### Cross-Cloud Pricing Comparison for " + f"`{self.gpu_name}`",
            "",
            "| Provider | Hourly Rate / GPU | Total Cluster / Hr | Cost / 1M Tokens | Monthly Dedicated (730h) |",
            "|:---|---:|---:|---:|---:|",
        ]

        gpu_id_key = self.gpu_id
        for p_name in ["runpod", "lambda", "aws", "gcp"]:
            p_rate = CLOUD_GPU_PRICING.get(p_name, {}).get(gpu_id_key)
            if p_rate is not None:
                p_cluster = p_rate * self.tensor_parallel
                p_c1m = (
                    (p_cluster / self.cost_estimate.tokens_per_hour) * 1e6
                    if self.cost_estimate.tokens_per_hour > 0
                    else 0.0
                )
                lines.append(
                    f"| **{p_name.upper()}** | ${p_rate:.2f} | ${p_cluster:.2f} | **${p_c1m:.4f}** | ${p_cluster * 730:.2f} |"
                )

        lines.extend(
            [
                "",
                "---",
                "",
                "## 6. Actionable Procurement & Sizing Recommendation",
                "",
                "> [!IMPORTANT]",
                f"> **Optimal Right-Sized GPU**: `{self.gpu_comparison.recommended_optimal_gpu or 'None (All OOM)'}`  ",
                "> Minimizes idle VRAM overhead while providing sufficient buffer for dynamic KV-cache scaling.  ",
                ">  ",
                f"> **Peak Performance GPU**: `{self.gpu_comparison.recommended_performance_gpu or 'None'}`  ",
                "> Delivers lowest time-per-output-token (TPOT) and highest aggregate batch throughput.",
                "",
                "---",
                "",
                "## 7. Mathematical & Analytical Foundations",
                "",
                "### KV-Cache Tensor Equation",
                "$$\\text{KV Bytes per Token} = 2 \\times L \\times H_{\\text{kv}} \\times D \\times B$$",
                "",
                "### Memory-Bandwidth Decode Roofline",
                "$$\\text{Aggregate Throughput (tokens/sec)} = \\frac{B \\times \\text{Memory Bandwidth (GB/s)} \\times 10^9 \\times \\eta}{W_{\\text{bytes}} + \\text{KV}_{\\text{bytes}}}$$",
                "",
                "### Unit Operational Economics",
                "$$\\text{Cost per 1M Tokens} = \\frac{\\text{Hourly Rental Rate}}{\\text{Tokens per Hour}} \\times 1,000,000$$",
                "",
            ]
        )
        return "\n".join(lines)


def generate_architecture_report(
    model: ModelArch,
    gpu: GPUProfile,
    precision: str = "fp16",
    kv_cache_dtype: str = "fp16",
    batch_size: int = 1,
    context_tokens: int = 2048,
    tensor_parallel: int = 1,
    provider: str = "runpod",
    custom_hourly_rate: float | None = None,
) -> ArchitectureReport:
    """Generate a complete, publication-ready architectural capacity and sizing report."""
    vram_res = estimate_vram_usage(
        model=model,
        gpu=gpu,
        precision=precision,
        kv_cache_dtype=kv_cache_dtype,
        batch_size=batch_size,
        context_tokens=context_tokens,
        tensor_parallel=tensor_parallel,
    )

    cost_res = estimate_serving_cost(
        model=model,
        gpu=gpu,
        precision=precision,
        kv_cache_dtype=kv_cache_dtype,
        batch_size=batch_size,
        context_tokens=context_tokens,
        tensor_parallel=tensor_parallel,
        provider=provider,
        custom_hourly_rate=custom_hourly_rate,
    )

    gpu_comp = compare_gpus_for_workload(
        model=model,
        precision=precision,
        kv_cache_dtype=kv_cache_dtype,
        batch_size=batch_size,
        context_tokens=context_tokens,
        tensor_parallel=tensor_parallel,
    )

    cloud_comp = compare_cloud_costs_for_workload(
        model=model,
        precision=precision,
        kv_cache_dtype=kv_cache_dtype,
        batch_size=batch_size,
        context_tokens=context_tokens,
        provider=provider,
        tensor_parallel=tensor_parallel,
    )

    total_params = model.calculate_total_parameters()

    return ArchitectureReport(
        model_name=model.name,
        gpu_name=gpu.display_name,
        gpu_id=gpu.name,
        precision=precision.lower(),
        kv_cache_dtype=kv_cache_dtype.lower(),
        batch_size=batch_size,
        context_tokens=context_tokens,
        tensor_parallel=tensor_parallel,
        provider=provider.lower(),
        vram_estimate=vram_res,
        cost_estimate=cost_res,
        gpu_comparison=gpu_comp,
        cloud_cost_comparison=cloud_comp,
        total_parameters=total_params,
        num_layers=model.num_layers,
        hidden_size=model.hidden_size,
        num_attention_heads=model.num_attention_heads,
        num_kv_heads=model.num_key_value_heads,
        gqa_ratio=model.gqa_ratio,
        mlp_type=model.mlp_type,
    )
